"""편집실 저장소 — Supabase(PostgreSQL)에 저장합니다.

Vercel 서버의 폴더는 읽기 전용이고 요청이 끝나면 사라지므로, 편집실이 만드는 것은 모두 DB에 둡니다.

  editor_docs    원고·팩트시트·검수·편집 검토·승인 기록 (뮤지션별 JSON)
                 + 홈 게시 상태 (kind='site', artist_id='archive' → 예전 artist-archive.json 내용)
  site_features  게시된 '오늘의 뮤지션' 기사 본문 HTML (뮤지션별). 현재 뮤지션과 지난 뮤지션 모두.
  site_assets    편집실에서 올린 뮤지션 사진
  site_history   게시 직전 상태 백업 (예전 articles/backups 폴더 역할)

DB에 아직 없는 것은 저장소 파일(articles/, images/, artist-archive.json, index.html)을 그대로 씁니다.
그래서 처음 전환할 때 기존 기사·사진·홈 화면이 그대로 보이고, 편집실에서 저장·게시한 것부터 DB에 쌓입니다.
"""
import json
import mimetypes
from pathlib import Path

from psycopg.types.json import Jsonb

from account_system.database import connect

ROOT = Path(__file__).resolve().parent.parent
_ready = False

SCHEMA = """
CREATE TABLE IF NOT EXISTS editor_docs (
    kind TEXT NOT NULL,
    artist_id TEXT NOT NULL,
    data JSONB NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT timezone('utc', now()),
    PRIMARY KEY (kind, artist_id)
);
CREATE TABLE IF NOT EXISTS site_features (
    artist_id TEXT PRIMARY KEY,
    block TEXT NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT timezone('utc', now())
);
CREATE TABLE IF NOT EXISTS site_assets (
    path TEXT PRIMARY KEY,
    content BYTEA NOT NULL,
    content_type TEXT NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT timezone('utc', now())
);
CREATE TABLE IF NOT EXISTS site_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stamp TEXT NOT NULL,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT timezone('utc', now())
);
ALTER TABLE editor_docs   ENABLE ROW LEVEL SECURITY;
ALTER TABLE site_features ENABLE ROW LEVEL SECURITY;
ALTER TABLE site_assets   ENABLE ROW LEVEL SECURITY;
ALTER TABLE site_history  ENABLE ROW LEVEL SECURITY
"""

# 예전 파일 위치 (DB에 아직 없을 때 읽기 전용으로 사용)
FILES = {'draft': 'articles/drafts/{id}.json', 'sheet': 'articles/research/{id}.json',
         'review': 'articles/reviews/{id}.json', 'editorial': 'articles/reviews/{id}-editorial.json',
         'approval': 'articles/approvals/{id}.json'}


class _Conn:
    """with 문으로 쓰는 짧은 DB 연결. 끝나면 commit, 오류면 rollback."""
    def __enter__(self):
        global _ready
        self.conn = connect()
        if not _ready:
            with self.conn.cursor() as cur:
                for statement in SCHEMA.split(';'):
                    if statement.strip():
                        cur.execute(statement)
            self.conn.commit()
            _ready = True
        return self.conn.cursor()

    def __exit__(self, kind, error, trace):
        try:
            self.conn.commit() if kind is None else self.conn.rollback()
        finally:
            self.conn.close()


def db():
    return _Conn()


def _file_json(rel):
    try:
        return json.loads((ROOT / rel).read_text(encoding='utf-8-sig'))
    except (FileNotFoundError, ValueError):
        return None


# ── 편집 기록 ──────────────────────────────────────────────
def get_doc(kind, artist_id, default=None):
    with db() as cur:
        cur.execute('SELECT data FROM editor_docs WHERE kind = %s AND artist_id = %s', (kind, artist_id))
        row = cur.fetchone()
    if row:
        return row['data']
    if kind in FILES:
        found = _file_json(FILES[kind].format(id=artist_id))
        if found is not None:
            return found
    return default


def put_doc(kind, artist_id, data):
    with db() as cur:
        cur.execute("""INSERT INTO editor_docs (kind, artist_id, data, updated_at)
                       VALUES (%s, %s, %s, timezone('utc', now()))
                       ON CONFLICT (kind, artist_id) DO UPDATE SET data = EXCLUDED.data, updated_at = EXCLUDED.updated_at""",
                    (kind, artist_id, Jsonb(data)))


def list_drafts():
    """원고가 있는 뮤지션: DB + 아직 DB로 옮기지 않은 파일. {id: draft}"""
    found = {}
    for f in sorted((ROOT / 'articles/drafts').glob('*.json')):
        data = _file_json(f'articles/drafts/{f.name}')
        if isinstance(data, dict):
            found[f.stem] = data
    with db() as cur:
        cur.execute("SELECT artist_id, data FROM editor_docs WHERE kind = 'draft' ORDER BY artist_id")
        for row in cur.fetchall():
            found[row['artist_id']] = row['data']
    return dict(sorted(found.items()))


# ── 게시 상태 ──────────────────────────────────────────────
def get_archive():
    with db() as cur:
        cur.execute("SELECT data FROM editor_docs WHERE kind = 'site' AND artist_id = 'archive'")
        row = cur.fetchone()
    if row:
        return row['data']
    return _file_json('artist-archive.json') or {'current': None, 'archive': []}


def get_feature(artist_id):
    with db() as cur:
        cur.execute('SELECT block FROM site_features WHERE artist_id = %s', (artist_id,))
        row = cur.fetchone()
    return row['block'] if row else None


def save_publication(archive, features, history, stamp):
    """게시 한 번을 통째로 저장합니다. 중간에 실패하면 아무것도 바뀌지 않습니다."""
    with db() as cur:
        for kind, name, content in history:
            cur.execute('INSERT INTO site_history (stamp, kind, name, content) VALUES (%s, %s, %s, %s)',
                        (stamp, kind, name, content))
        for artist_id, block in features.items():
            cur.execute("""INSERT INTO site_features (artist_id, block, updated_at) VALUES (%s, %s, timezone('utc', now()))
                           ON CONFLICT (artist_id) DO UPDATE SET block = EXCLUDED.block, updated_at = EXCLUDED.updated_at""",
                        (artist_id, block))
        cur.execute("""INSERT INTO editor_docs (kind, artist_id, data, updated_at) VALUES ('site', 'archive', %s, timezone('utc', now()))
                       ON CONFLICT (kind, artist_id) DO UPDATE SET data = EXCLUDED.data, updated_at = EXCLUDED.updated_at""",
                    (Jsonb(archive),))


# ── 사진 ───────────────────────────────────────────────────
def put_asset(path, content, content_type, remove=()):
    with db() as cur:
        for old in remove:
            cur.execute('DELETE FROM site_assets WHERE path = %s', (old,))
        cur.execute("""INSERT INTO site_assets (path, content, content_type, updated_at) VALUES (%s, %s, %s, timezone('utc', now()))
                       ON CONFLICT (path) DO UPDATE SET content = EXCLUDED.content, content_type = EXCLUDED.content_type,
                       updated_at = EXCLUDED.updated_at""", (path, content, content_type))


def get_asset(path):
    """(내용, 종류) — DB에 올린 사진이 먼저, 없으면 저장소 파일."""
    with db() as cur:
        cur.execute('SELECT content, content_type FROM site_assets WHERE path = %s', (path,))
        row = cur.fetchone()
    if row:
        return bytes(row['content']), row['content_type']
    file = (ROOT / path).resolve()
    if file.is_relative_to(ROOT) and file.is_file():
        return file.read_bytes(), mimetypes.guess_type(file.name)[0] or 'application/octet-stream'
    return None


def asset_exists(path):
    with db() as cur:
        cur.execute('SELECT 1 FROM site_assets WHERE path = %s', (path,))
        if cur.fetchone():
            return True
    return (ROOT / path).is_file()


# ── 공개 페이지 (DB의 게시 내용 + 저장소의 최신 디자인) ─────────
def home_page():
    """index.html에 DB의 현재 '오늘의 뮤지션' 기사를 끼워 넣습니다. 게시 기록이 없으면 파일 그대로."""
    from . import publish
    page = (ROOT / 'index.html').read_text(encoding='utf-8')
    current = (get_archive() or {}).get('current')
    block = get_feature(current['id']) if current else None
    if not block:
        return page
    start, end, _ = publish.home_block(page)
    return publish.splice_home(page, start, end, block)


def archive_page(slug):
    """지난 뮤지션 페이지. DB에 기사가 있으면 저장소의 아카이브 틀로 만들고, 없으면 파일 그대로."""
    from . import publish
    data = get_archive() or {}
    entry = next((a for a in data.get('archive', []) if a.get('id') == slug), None)
    block = get_feature(slug) if entry else None
    if block:
        template = publish.TEMPLATE.read_text(encoding='utf-8')
        return publish.archive_page(template, block, entry.get('name', ''), entry.get('nameKo', ''))
    file = ROOT / f'artist-{slug}.html'
    return file.read_text(encoding='utf-8') if file.is_file() else None


def migrate_files(force=False):
    """articles/ 폴더의 기존 기록을 DB로 복사합니다. (이미 DB에 있으면 건너뜀, force=True면 덮어씀)"""
    copied, skipped = [], []
    for kind, pattern in FILES.items():
        folder = ROOT / Path(pattern).parent
        for f in sorted(folder.glob('*.json')):
            stem = f.stem
            if kind == 'review' and stem.endswith('-editorial'):
                continue
            if kind == 'editorial':
                if not stem.endswith('-editorial'):
                    continue
                stem = stem[:-len('-editorial')]
            data = _file_json(str(f.relative_to(ROOT)))
            if data is None:
                continue
            with db() as cur:
                cur.execute('SELECT 1 FROM editor_docs WHERE kind = %s AND artist_id = %s', (kind, stem))
                exists = cur.fetchone()
            if exists and not force:
                skipped.append(f'{kind}/{stem}')
                continue
            put_doc(kind, stem, data)
            copied.append(f'{kind}/{stem}')
    return copied, skipped


if __name__ == '__main__':
    import sys
    done, kept = migrate_files('--force' in sys.argv)
    print(f'DB로 복사: {len(done)}개' + (' — ' + ', '.join(done) if done else ''))
    if kept:
        print(f'이미 DB에 있어 건너뜀: {len(kept)}개 (덮어쓰려면 --force)')

#!/usr/bin/env python3
"""곡 원본(data_backup.json) → db/todays_rock.sql 만들기

사용법 (저장소 맨 위 폴더에서):
    python db/build_songs_sql.py          # db/todays_rock.sql 새로 만들기
    python db/build_songs_sql.py --check  # 파일을 쓰지 않고, 지금 SQL이 JSON과 같은지만 확인

- 곡 번호(id)는 data_backup.json의 순서입니다(첫 곡 = 1). 좋아요 기록이 곡 번호로 저장되므로,
  기존 곡의 순서를 바꾸거나 중간에서 지우지 말고 새 곡은 맨 뒤에 추가하세요.
- 만들기 전에 필수 값, 에너지(1~5), 기분·날씨 값, 같은 제목+가수 중복을 검사합니다.
- 만든 SQL은 Supabase SQL Editor에 붙여 실행합니다. 곡 테이블을 지우고 다시 만들며 회원 테이블은 그대로 둡니다.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'data_backup.json'
TARGET = ROOT / 'db' / 'todays_rock.sql'
CHUNK = 100   # INSERT 한 문장에 넣는 곡 수

MOODS = {'calm', 'excited', 'focused', 'blue', 'tired', 'frustrated'}
WEATHERS = {'clear', 'cloudy', 'rain', 'snow'}
LIMITS = {'title': 200, 'artist': 200, 'genre': 100, 'theme': 255, 'tone': 255, 'reason': 500, 'lyricsUrl': 500}

HEAD = '-- 「오늘의 록」 곡 데이터 — PostgreSQL / Supabase용\n--\n-- ※ 이 파일은 db/build_songs_sql.py가 data_backup.json(곡 원본)으로 만듭니다. 직접 고치지 마세요.\n--   곡을 추가·수정하려면 data_backup.json을 고친 뒤 `python db/build_songs_sql.py`를 실행합니다.\n--\n-- 실행 방법 (둘 중 하나)\n--   Supabase: 대시보드 → SQL Editor → New query → 이 파일 내용 전체 붙여넣기 → Run\n--   psql:     psql "$DATABASE_URL" -f db/todays_rock.sql\n--\n-- 주의: 곡 관련 뷰·테이블(songs, song_moods, song_weathers, v_songs)을 지우고 다시 만듭니다.\n--       회원 테이블(account_로 시작)은 곡 테이블을 참조하지 않으므로 그대로 유지됩니다.\n\nBEGIN;\n\n-- 다시 실행해도 되도록 기존 뷰·테이블 정리\nDROP VIEW  IF EXISTS v_songs;\nDROP TABLE IF EXISTS song_weathers;\nDROP TABLE IF EXISTS song_moods;\nDROP TABLE IF EXISTS songs;\n\n-- 1) 곡 정보\nCREATE TABLE songs (\n  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  title      VARCHAR(200) NOT NULL,\n  artist     VARCHAR(200) NOT NULL,\n  year       SMALLINT     NOT NULL,\n  genre      VARCHAR(100) NOT NULL,\n  energy     SMALLINT     NOT NULL CHECK (energy BETWEEN 1 AND 5),\n  theme      VARCHAR(255),\n  tone       VARCHAR(255),\n  reason     VARCHAR(500),\n  lyrics_url VARCHAR(500),\n  CONSTRAINT uq_title_artist UNIQUE (title, artist)\n);\n\n-- 2) 곡별 기분 (한 곡에 여러 개)\nCREATE TABLE song_moods (\n  song_id INTEGER NOT NULL REFERENCES songs(id) ON DELETE CASCADE,\n  mood    TEXT    NOT NULL CHECK (mood IN (\'calm\',\'excited\',\'focused\',\'blue\',\'tired\',\'frustrated\')),\n  PRIMARY KEY (song_id, mood)\n);\n\n-- 3) 곡별 날씨 (한 곡에 여러 개)\nCREATE TABLE song_weathers (\n  song_id INTEGER NOT NULL REFERENCES songs(id) ON DELETE CASCADE,\n  weather TEXT    NOT NULL CHECK (weather IN (\'clear\',\'cloudy\',\'rain\',\'snow\')),\n  PRIMARY KEY (song_id, weather)\n);\n\n'

TAIL = "-- id를 직접 넣었으므로 다음 자동 번호를 마지막 id 뒤로 맞춥니다.\nSELECT setval(pg_get_serial_sequence('songs', 'id'), (SELECT MAX(id) FROM songs));\n\n-- 4) 웹앱의 data.json과 같은 모양으로 보는 뷰 (기분·날씨는 쉼표로 이은 글자)\nCREATE VIEW v_songs WITH (security_invoker = true) AS\nSELECT s.id, s.title, s.artist, s.year, s.genre, s.energy,\n       (SELECT string_agg(mood,    ',' ORDER BY mood)    FROM song_moods    WHERE song_id = s.id) AS moods,\n       (SELECT string_agg(weather, ',' ORDER BY weather) FROM song_weathers WHERE song_id = s.id) AS weathers,\n       s.theme, s.tone, s.reason, s.lyrics_url\nFROM songs s;\n\n-- 5) Supabase 보안: 브라우저용 공개 API(anon 키)로 이 테이블을 읽거나 쓰지 못하게 막습니다.\n--    서버(FastAPI)는 DB 비밀번호로 직접 접속하므로 영향을 받지 않습니다.\nALTER TABLE songs         ENABLE ROW LEVEL SECURITY;\nALTER TABLE song_moods    ENABLE ROW LEVEL SECURITY;\nALTER TABLE song_weathers ENABLE ROW LEVEL SECURITY;\n\nCOMMIT;\n\n-- 6) 확인용 (결과: {songs} / {moods} / {weathers})\nSELECT\n  (SELECT COUNT(*) FROM songs)         AS songs,\n  (SELECT COUNT(*) FROM song_moods)    AS moods,\n  (SELECT COUNT(*) FROM song_weathers) AS weathers;\n"


def check(songs):
    errors, seen = [], {}
    for i, s in enumerate(songs, 1):
        where = f'{i}번 곡({s.get("artist")} - {s.get("title")})'
        for key in ('title', 'artist', 'year', 'genre', 'energy', 'moods', 'weathers'):
            if s.get(key) in (None, '', []):
                errors.append(f'{where}: {key} 값이 없습니다.')
        for key, limit in LIMITS.items():
            if len(str(s.get(key) or '')) > limit:
                errors.append(f'{where}: {key}가 {limit}자를 넘습니다.')
        if not isinstance(s.get('year'), int):
            errors.append(f'{where}: year는 숫자여야 합니다.')
        if s.get('energy') not in (1, 2, 3, 4, 5):
            errors.append(f'{where}: energy는 1~5여야 합니다.')
        for key, allowed in (('moods', MOODS), ('weathers', WEATHERS)):
            values = s.get(key) or []
            wrong = [v for v in values if v not in allowed]
            if wrong:
                errors.append(f'{where}: {key}에 쓸 수 없는 값 {wrong} (가능: {", ".join(sorted(allowed))})')
            if len(set(values)) != len(values):
                errors.append(f'{where}: {key}에 같은 값이 두 번 있습니다.')
        pair = (s.get('title'), s.get('artist'))
        if pair in seen:
            errors.append(f'{where}: {seen[pair]}번 곡과 제목·가수가 같습니다.')
        seen.setdefault(pair, i)
    return errors


def q(value):
    return 'NULL' if value in (None, '') else "'" + str(value).replace("'", "''") + "'"


def build(songs):
    out = [HEAD, f'-- 곡 데이터 ({len(songs)}곡)\n']
    for start in range(0, len(songs), CHUNK):
        rows = [f"({i}, {q(s['title'])}, {q(s['artist'])}, {s['year']}, {q(s['genre'])}, {s['energy']}, "
                f"{q(s.get('theme'))}, {q(s.get('tone'))}, {q(s.get('reason'))}, {q(s.get('lyricsUrl'))})"
                for i, s in enumerate(songs[start:start + CHUNK], start + 1)]
        out.append('INSERT INTO songs (id, title, artist, year, genre, energy, theme, tone, reason, lyrics_url) VALUES\n'
                   + ',\n'.join(rows) + ';\n\n')
    moods = [f"({i}, {q(m)})" for i, s in enumerate(songs, 1) for m in s['moods']]
    weathers = [f"({i}, {q(w)})" for i, s in enumerate(songs, 1) for w in s['weathers']]
    out.append('INSERT INTO song_moods (song_id, mood) VALUES\n' + ',\n'.join(moods) + ';\n\n')
    out.append('INSERT INTO song_weathers (song_id, weather) VALUES\n' + ',\n'.join(weathers) + ';\n\n')
    out.append(TAIL.format(songs=len(songs), moods=len(moods), weathers=len(weathers)))
    return ''.join(out)


def main():
    songs = json.loads(SOURCE.read_text(encoding='utf-8'))
    errors = check(songs)
    if errors:
        print(f'곡 원본에 문제가 {len(errors)}개 있어 SQL을 만들지 않았습니다.')
        print('\n'.join('- ' + e for e in errors[:30]))
        sys.exit(1)
    sql = build(songs)
    if '--check' in sys.argv:
        same = TARGET.exists() and TARGET.read_text(encoding='utf-8') == sql
        print('db/todays_rock.sql이 곡 원본과 같습니다.' if same else 'db/todays_rock.sql이 곡 원본과 다릅니다. 스크립트를 실행해 다시 만드세요.')
        sys.exit(0 if same else 1)
    TARGET.write_text(sql, encoding='utf-8', newline='\n')
    print(f'db/todays_rock.sql을 만들었습니다: 곡 {len(songs)}곡, 기분 {sum(len(s["moods"]) for s in songs)}개, 날씨 {sum(len(s["weathers"]) for s in songs)}개')


if __name__ == '__main__':
    main()

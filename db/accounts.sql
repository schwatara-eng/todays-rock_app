-- 회원 전용 스키마 (PostgreSQL / Supabase). 기존 곡/기사/회원 데이터를 삭제하지 않습니다.
-- 보통은 직접 실행할 필요 없이 `python -m account_system.manage init`(또는 create-admin)이 실행합니다.
-- 시간 칸은 모두 UTC 기준 시각(timestamp)으로 저장합니다.

CREATE TABLE IF NOT EXISTS account_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    display_name VARCHAR(40) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'reporter', 'admin')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT timezone('utc', now()),
    updated_at TIMESTAMP NOT NULL DEFAULT timezone('utc', now()),
    last_login_at TIMESTAMP NULL
);

-- 이메일은 대소문자를 구분하지 않고 한 번만 가입할 수 있습니다.
CREATE UNIQUE INDEX IF NOT EXISTS uq_account_email ON account_users (lower(email));

CREATE TABLE IF NOT EXISTS account_sessions (
    token_hash CHAR(64) NOT NULL PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES account_users(id) ON DELETE CASCADE,
    csrf_token CHAR(43) NOT NULL,
    expires_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_account_session_user ON account_sessions (user_id);
CREATE INDEX IF NOT EXISTS ix_account_session_expiry ON account_sessions (expires_at);

-- song_id는 songs를 참조하지 않습니다. (곡 SQL을 다시 실행해도 좋아요 기록이 남도록)
CREATE TABLE IF NOT EXISTS account_likes (
    user_id BIGINT NOT NULL REFERENCES account_users(id) ON DELETE CASCADE,
    song_id INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT timezone('utc', now()),
    PRIMARY KEY (user_id, song_id)
);
CREATE INDEX IF NOT EXISTS ix_account_likes_date ON account_likes (user_id, created_at);

CREATE TABLE IF NOT EXISTS account_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL,
    target_id BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    old_value VARCHAR(40) NOT NULL,
    new_value VARCHAR(40) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT timezone('utc', now())
);
CREATE INDEX IF NOT EXISTS ix_account_audit_date ON account_audit (created_at);

CREATE TABLE IF NOT EXISTS account_auth_limits (
    bucket_hash CHAR(64) NOT NULL PRIMARY KEY,
    attempts INTEGER NOT NULL DEFAULT 0,
    window_start TIMESTAMP NOT NULL
);

-- Supabase 보안: 브라우저용 공개 API(anon 키)로 회원 정보에 접근하지 못하게 막습니다.
-- 서버(FastAPI)는 DB 비밀번호로 직접 접속하므로 영향을 받지 않습니다.
ALTER TABLE account_users       ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_sessions    ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_likes       ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_audit       ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_auth_limits ENABLE ROW LEVEL SECURITY;

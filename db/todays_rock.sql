CREATE VIEW v_songs AS
SELECT s.id, s.title, s.artist, s.year, s.genre, s.energy,
       (SELECT GROUP_CONCAT(mood    ORDER BY mood)    FROM song_moods    WHERE song_id = s.id) AS moods,
       (SELECT GROUP_CONCAT(weather ORDER BY weather) FROM song_weathers WHERE song_id = s.id) AS weathers,
       s.theme, s.tone, s.reason, s.lyrics_url
FROM songs s;


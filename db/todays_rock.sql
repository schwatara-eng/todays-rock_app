CREATE DATABASE IF NOT EXISTS todays_rock
  DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE todays_rock;

-- 다시 실행해도 되도록 기존 테이블 정리 (자식 테이블부터)
DROP VIEW  IF EXISTS v_songs;
DROP TABLE IF EXISTS song_weathers;
DROP TABLE IF EXISTS song_moods;
DROP TABLE IF EXISTS songs;

-- 1) 곡 정보
CREATE TABLE songs (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  title      VARCHAR(200) NOT NULL,
  artist     VARCHAR(200) NOT NULL,
  year       SMALLINT     NOT NULL,
  genre      VARCHAR(100) NOT NULL,
  energy     TINYINT      NOT NULL CHECK (energy BETWEEN 1 AND 5),
  theme      VARCHAR(255),
  tone       VARCHAR(255),
  reason     VARCHAR(500),
  lyrics_url VARCHAR(500),
  UNIQUE KEY uq_title_artist (title, artist)
);

-- 2) 곡별 기분 (한 곡에 여러 개)
CREATE TABLE song_moods (
  song_id INT NOT NULL,
  mood    ENUM('calm','excited','focused','blue','tired','frustrated') NOT NULL,
  PRIMARY KEY (song_id, mood),
  FOREIGN KEY (song_id) REFERENCES songs(id) ON DELETE CASCADE
);

-- 3) 곡별 날씨 (한 곡에 여러 개)
CREATE TABLE song_weathers (
  song_id INT NOT NULL,
  weather ENUM('clear','cloudy','rain','snow') NOT NULL,
  PRIMARY KEY (song_id, weather),
  FOREIGN KEY (song_id) REFERENCES songs(id) ON DELETE CASCADE
);

